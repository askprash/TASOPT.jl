"""
summarize_optimizer_benchmark.jl

Builds test/benchmark_results/summary.md from the run files written by
test/benchmark_optimizers_fair.jl plus the saved Fortran simpop log.

  julia test/summarize_optimizer_benchmark.jl      (stdlib only)
"""

using Printf, Statistics

const DIR = joinpath(@__DIR__, "benchmark_results")
const LBF2N = 4.44822
const FLOG = joinpath(DIR, "fortran", "fortran_opt_3000_rerun.log")
const FTIME = joinpath(DIR, "fortran", "time.txt")

# ── Julia runs ───────────────────────────────────────────────────
function read_csv(path)
    lines = readlines(path)
    hdr = split(lines[1], ",")
    rows = [split(l, ",") for l in lines[2:end] if !isempty(l)]
    return hdr, rows
end

struct Run
    id::String; opt::String; start::Int; wall::Float64; sizing::Float64; nevals::Int
    f::Float64; Wfuel::Float64; viol::Vector{Float64}; maxviol::Float64; reason::String
    trace::Vector{Float64}      # best-so-far per evaluation
end

function load_runs()
    hdr, rows = read_csv(joinpath(DIR, "runs_summary.csv"))
    runs = Run[]
    for r in rows
        d = Dict(zip(hdr, r))
        _, trows = read_csv(joinpath(DIR, "evals_$(d["run"]).csv"))
        best = [parse(Float64, t[3]) for t in trows]
        push!(runs, Run(d["run"], d["optimizer"], parse(Int, d["start"]), parse(Float64, d["wall_s"]),
                        parse(Float64, d["sizing_s"]), parse(Int, d["nevals"]), parse(Float64, d["f_final"]),
                        parse(Float64, d["Wfuel_N"]),
                        parse.(Float64, [d["span_viol"], d["lBF_viol"], d["fuel_viol"], d["gtoc_viol"]]),
                        parse(Float64, d["max_viol"]), strip(d["reason"], '"'), best))
    end
    return runs
end

evals_to(trace, target) = (i = findfirst(<=(target), trace); i === nothing ? missing : i)

# ── Fortran simpop log ───────────────────────────────────────────
function fortran_run()
    fobj = Float64[]; last = nothing
    for l in eachline(FLOG)
        m = match(r"^\s*j\s+\d+\s+\S+\s+(\S+)", l)
        # step number and dFrel can run together when dFrel is negative, e.g. "! 501-0.336E+04"
        m === nothing && (m = match(r"^\s*[rec!]\s*\d+\s*-?[\d.]+(?:E[+-]\d+)?\s+(\S+)", l))
        m === nothing && continue
        f = tryparse(Float64, m.captures[1])
        f === nothing && continue
        push!(fobj, f * LBF2N)
        if startswith(strip(l), "!"); last = split(replace(strip(l), r"^!" => "! "))[2:end]; end
    end
    best = accumulate(min, fobj)
    t = read(FTIME, String)
    wall = parse(Float64, match(r"([\d.]+) total", t).captures[1])
    # final line columns: step dFrel Fobj Wfuel WMTO b lBF cd CL AR sweep ...
    Wfuel = parse(Float64, last[4]) * LBF2N
    b = parse(Float64, last[6]); lBF = parse(Float64, last[7])
    return (; wall, nevals = length(fobj), f = fobj[end], Wfuel, b, lBF, trace = best,
            span_viol = b / 117.5 - 1, lBF_viol = lBF / 8000 - 1)
end

# ── Report ───────────────────────────────────────────────────────
function main()
    runs = load_runs()
    F = fortran_run()
    io = IOBuffer()
    println(io, "# Optimizer comparison: warm-started Julia vs Fortran simpop\n")
    println(io, "Generated by `test/summarize_optimizer_benchmark.jl` from `test/benchmark_results/`.")
    println(io, "Objective = fuel weight [N] + fobj.f penalties. Constraint violations are relative and positive when violated")
    println(io, "(span: b/bmax-1, BFL: lBF/8000ft-1, fuel: Wfuel/(rWfmax Wfmax)-1, top-of-climb: 1-gamma/gtocmin).")
    println(io, "A run is called feasible when its largest violation is at most 1e-3.\n")

    fbest_all = minimum(r.f for r in runs)
    println(io, "## Per-run results\n")
    println(io, "| run | evals | wall [s] | ms/eval | best objective [N] | Wfuel [N] | span | BFL | fuel vol | gtoc | feasible | stop reason |")
    println(io, "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|:-:|---|")
    for r in runs
        @printf(io, "| %s | %d | %.1f | %.1f | %.1f | %.1f | %+.2e | %+.2e | %+.2e | %+.2e | %s | %s |\n", r.id, r.nevals, r.wall,
                1e3 * r.wall / r.nevals, r.f, r.Wfuel, r.viol..., r.maxviol <= 1e-3 ? "yes" : "no", r.reason)
    end
    @printf(io, "| **Fortran simpop (start 0)** | %d | %.1f | %.1f | %.1f | %.1f | %+.2e | %+.2e | n/a | n/a | no | converged, step 1796 |\n",
            F.nevals, F.wall, 1e3 * F.wall / F.nevals, F.f, F.Wfuel, F.span_viol, F.lBF_viol)

    println(io, "\nFortran fuel-volume and top-of-climb values are not printed in its log. Its penalty (Fobj - Wfuel) is",
            @sprintf(" %.0f N, which comes from the span and BFL violations listed (fuel volume and top-of-climb are inactive or small).\n", F.f - F.Wfuel))

    println(io, "## Per-optimizer summary (4 starts each)\n")
    println(io, "Evaluations-to-target use the best-so-far trace. Targets are relative to the best objective found by any Julia run ($(round(fbest_all, digits=1)) N).\n")
    println(io, "| optimizer | median wall [s] | median evals | median ms/eval | best objective [N] | median objective [N] | feasible runs | median evals to within 1% | median evals to within 0.1% |")
    println(io, "|---|---:|---:|---:|---:|---:|:-:|---:|---:|")
    opts = unique(r.opt for r in runs)
    fmtmed(v) = (v = collect(skipmissing(v)); isempty(v) ? "never" : @sprintf("%.0f", median(v)) * (length(v) < 4 ? " ($(length(v))/4 runs)" : ""))
    for o in opts
        rs = filter(r -> r.opt == o, runs)
        e1 = [evals_to(r.trace, fbest_all * 1.01) for r in rs]
        e2 = [evals_to(r.trace, fbest_all * 1.001) for r in rs]
        @printf(io, "| %s | %.1f | %.0f | %.1f | %.1f | %.1f | %d/%d | %s | %s |\n", o, median(r.wall for r in rs),
                median(r.nevals for r in rs), median(1e3 * r.wall / r.nevals for r in rs), minimum(r.f for r in rs),
                median(r.f for r in rs), count(r -> r.maxviol <= 1e-3, rs), length(rs), fmtmed(e1), fmtmed(e2))
    end
    ef1 = evals_to(F.trace, F.f * 1.01); ef2 = evals_to(F.trace, F.f * 1.001)
    @printf(io, "| Fortran simpop (own final value as target) | %.1f | %d | %.1f | %.1f | %.1f | 0/1 | %d | %d |\n",
            F.wall, F.nevals, 1e3 * F.wall / F.nevals, F.f, F.f, ef1, ef2)

    # verdicts
    feas = filter(r -> r.maxviol <= 1e-3, runs)
    println(io, "\n## Verdicts\n")
    rb = runs[argmin([r.f for r in runs])]
    @printf(io, "* Lowest penalized objective over all Julia runs: **%s**, %.1f N after %d evaluations (%.1f s).\n", rb.id, rb.f, rb.nevals, rb.wall)
    if isempty(feas)
        println(io, "* No Julia run ended with all violations <= 1e-3, so no optimizer reaches a strictly feasible optimum with the penalty method alone.")
        rl = runs[argmin([r.maxviol for r in runs])]
        @printf(io, "* Smallest violation: %s (%.2e), objective %.1f N.\n", rl.id, rl.maxviol, rl.f)
    else
        rf = feas[argmin([r.Wfuel for r in feas])]
        @printf(io, "* Lowest fuel weight among feasible runs: **%s**, Wfuel %.1f N, %d evaluations.\n", rf.id, rf.Wfuel, rf.nevals)
    end
    # fewest evaluations to reach within 0.1% of best
    cand = [(r, evals_to(r.trace, fbest_all * 1.001)) for r in runs]
    cand = filter(c -> c[2] !== missing, cand)
    if !isempty(cand)
        c = cand[argmin([x[2] for x in cand])]
        @printf(io, "* Fewest evaluations to come within 0.1%% of the best Julia objective: **%s** (%d evaluations).\n", c[1].id, c[2])
    end
    @printf(io, "* Fortran simpop wall time: %.1f s for %d evaluations (%.1f ms each).\n", F.wall, F.nevals, 1e3 * F.wall / F.nevals)
    for o in opts
        rs = filter(r -> r.opt == o, runs)
        @printf(io, "* %s: median wall %.1f s, so %s Fortran wall time.\n", o, median(r.wall for r in rs),
                median(r.wall for r in rs) < F.wall ? "**faster than**" : "slower than")
    end
    msj = median(1e3 * r.wall / r.nevals for r in runs)
    @printf(io, "\n## Notes\n\n* Cost per evaluation: Julia median %.1f ms (warm-started, initwgt=true after the first call) against %.1f ms for Fortran, a ratio of %.1f. ",
            msj, 1e3 * F.wall / F.nevals, msj / (1e3 * F.wall / F.nevals))
    println(io, "The 9.5 ms warm figure measured near the converged baseline was not reproduced along the optimization path (the cause was not investigated; trial points probably need more weight iterations). Julia's wall-time advantage therefore comes from needing fewer evaluations, not from faster sizing.")
    println(io, "* All penalty-method optimizers settle where the quadratic penalties are partly violated (see the violation columns). The penalty weights, not the optimizer, set this; Fortran simpop ends the same way (span +0.23%, BFL +1.4%).")
    println(io, "* Runs that hit a failed sizing (non-finite objective or exception) are counted in `nfail` in `runs_summary.csv`; the harness rebuilds the aircraft after such a failure so later evaluations are not contaminated.")
    println(io, "* The Julia starting point differs from Fortran's: `example/737_compare_input.toml` has Tt4 1533/1487 K, while the Fortran run starts at 1833/1587 K; the committed copy uses the Fortran values.")
    println(io, "\nThe Julia and Fortran sizing models do not give identical numbers at the same design point (the starting objective is 263200 N in Julia against 244870 N in Fortran), so absolute objective values should not be compared across codes. Wall time, evaluation counts and constraint behavior are comparable.")
    write(joinpath(DIR, "summary.md"), String(take!(io)))
    println("wrote ", joinpath(DIR, "summary.md"))
end

main()
